"""Inventory the locked environment and preserve installed dependency license notices."""

import hashlib
import json
import re
import tomllib
from importlib import metadata
from pathlib import Path


def normalized(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def build(root):
    lock_bytes = (root / "uv.lock").read_bytes()
    lock = tomllib.loads(lock_bytes.decode())
    project = tomllib.loads((root / "pyproject.toml").read_text("utf-8"))["project"]
    packages = {item["name"]: item for item in lock["package"]}
    app = packages[project["name"]]
    runtime, pending = set(), [item["name"] for item in app.get("dependencies", [])]
    while pending:
        name = pending.pop()
        if name not in runtime:
            runtime.add(name)
            pending.extend(item["name"] for item in packages[name].get("dependencies", []))
    components, notices, rows = [], [], []
    for name, item in sorted(packages.items()):
        if name == project["name"]:
            continue
        installed = metadata.distribution(name)
        if installed.version != item["version"]:
            raise ValueError(f"Run uv sync --locked before inventory: {name}")
        info = installed.metadata
        expression = info.get("License-Expression")
        label = (
            expression
            or info.get("License")
            or "; ".join(
                value for value in info.get_all("Classifier", []) if value.startswith("License ::")
            )
            or "Not declared in installed metadata"
        )
        purl = f"pkg:pypi/{normalized(name)}@{item['version']}"
        component = {
            "type": "library",
            "bom-ref": purl,
            "purl": purl,
            "name": name,
            "version": item["version"],
            "licenses": [{"expression": expression}]
            if expression
            else [{"license": {"name": label}}],
            "properties": [
                {
                    "name": "kelly:dependency-scope",
                    "value": "runtime" if name in runtime else "development",
                }
            ],
        }
        if source := item.get("sdist"):
            component["externalReferences"] = [
                {
                    "type": "distribution",
                    "url": source["url"],
                    "hashes": [
                        {"alg": "SHA-256", "content": source["hash"].removeprefix("sha256:")}
                    ],
                }
            ]
        components.append(component)
        rows.append(
            f"| {name} | {item['version']} | {'runtime' if name in runtime else 'development'} | {label.replace('|', '/').replace(chr(10), ' ')} |"
        )
        for file in sorted(installed.files or [], key=str):
            filename = Path(str(file)).name.upper()
            if filename.startswith(
                ("LICENSE", "LICENCE", "COPYING", "COPYRIGHT", "NOTICE", "THIRDPARTYNOTICES")
            ) and not filename.endswith(".PY"):
                content = installed.locate_file(file).read_text("utf-8", errors="replace")
                notices.append(
                    f"\n{'=' * 72}\n{name} {item['version']} — {filename}\n{'=' * 72}\n{content}"
                )
    bom = {
        "$schema": "http://cyclonedx.org/schema/bom-1.6.schema.json",
        "bomFormat": "CycloneDX",
        "specVersion": "1.6",
        "version": 1,
        "metadata": {
            "component": {
                "type": "application",
                "name": project["name"],
                "version": project["version"],
            },
            "properties": [
                {"name": "kelly:uv-lock-sha256", "value": hashlib.sha256(lock_bytes).hexdigest()}
            ],
        },
        "components": components,
    }
    # All resolved runtime/development packages, not an installed-Windows-only dependency graph.
    target = root / "src/kelly/licenses"
    target.mkdir(exist_ok=True)
    (target / "sbom.json").write_text(json.dumps(bom, indent=2, ensure_ascii=False) + "\n", "utf-8")
    (target / "third-party.txt").write_text(
        "Locked dependency notices. Vendored Office notices remain in _vendor/office/LICENSE.\n"
        + "\n".join(notices),
        "utf-8",
    )
    (root / "docs/DEPENDENCIES.md").write_text(
        "# Dependencies and licenses\n\nGenerated by `uv run --locked python scripts/build_sbom.py` from `uv.lock` and matching installed distribution metadata. "
        "Runtime and development dependencies are both listed. This is an inventory, not a vulnerability audit. "
        "The [CycloneDX 1.6 SBOM](../src/kelly/licenses/sbom.json) includes the lock hash and locked source-archive hashes; "
        "[license notices](../src/kelly/licenses/third-party.txt) are included in the wheel. "
        "[Vendored Office code](THIRD_PARTY.md) has its own preserved MIT notice.\n\n"
        "| Package | Version | Scope | Declared license |\n|---|---|---|---|\n"
        + "\n".join(rows)
        + "\n",
        "utf-8",
    )
    return len(components)


if __name__ == "__main__":
    print(f"Inventoried {build(Path(__file__).resolve().parents[1])} locked dependencies")
